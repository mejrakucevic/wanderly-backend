import { readFile, writeFile } from 'node:fs/promises';

// This snapshot contains columns/defaults only. Do not infer foreign keys, enums,
// unique constraints, or deletion behavior from column names.
const columns = JSON.parse((await readFile(new URL('../supabase/schema/columns.json', import.meta.url), 'utf8')).replace(/^\uFEFF/, ''));
const types = {
  uuid: 'string', text: 'string', date: 'string',
  'timestamp with time zone': 'string', 'time without time zone': 'string',
  numeric: 'number', integer: 'number', 'double precision': 'number', boolean: 'boolean',
};
const tables = [...new Set(columns.map((column) => column.table_name))];
const lines = [
  '// Generated by npm run types:database from the supplied column snapshot.',
  '// Relationships/constraints are unknown; replace with Supabase CLI output when available.',
  'export type Database = {', '  public: {', '    Tables: {',
];
for (const table of tables) {
  const tableColumns = columns.filter((column) => column.table_name === table);
  lines.push(`      ${table}: {`);
  for (const mode of ['Row', 'Insert', 'Update']) {
    lines.push(`        ${mode}: {`);
    for (const column of tableColumns) {
      const type = types[column.data_type];
      if (!type) throw new Error(`Unsupported database type: ${column.data_type}`);
      const optional = mode === 'Update' || (mode === 'Insert' && (column.is_nullable === 'YES' || column.column_default !== null));
      lines.push(`          ${column.column_name}${optional ? '?' : ''}: ${type}${column.is_nullable === 'YES' ? ' | null' : ''};`);
    }
    lines.push('        };');
  }
  lines.push('        Relationships: [];', '      };');
}
lines.push('    };', '    Views: { [_ in never]: never };', '    Functions: { [_ in never]: never };', '    Enums: { [_ in never]: never };', '    CompositeTypes: { [_ in never]: never };', '  };', '};', '');
await writeFile(new URL('../src/types/database.ts', import.meta.url), lines.join('\n'));
